const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const path=require('node:path');
const js=fs.readFileSync(path.join(__dirname,'../portfolio-agent.js'),'utf8');
const css=fs.readFileSync(path.join(__dirname,'../portfolio-agent.css'),'utf8');
const begin=js.indexOf('let mobileScrollLock=null;');
const end=js.indexOf('\nfunction closeAgent(){',begin);
assert(begin>=0&&end>begin,'Find the mobile viewport implementation');
const classes=()=>({values:new Set(),add(x){this.values.add(x)},remove(x){this.values.delete(x)}});
const props=new Map();
const body={style:{overflow:'visible'},classList:classes()};
const html={style:{overflow:'visible'},classList:classes()};
let stops=0,starts=0;
const viewport={height:430,offsetTop:175,addEventListener(){}};
const win={visualViewport:viewport,innerHeight:850,ltLenis:{stop(){stops++},start(){starts++}},addEventListener(){}};
const dialog={open:true,style:{setProperty(k,v){props.set(k,v)},removeProperty(k){props.delete(k)}},classList:{toggle(k,v){this[k]=v},remove(k){this[k]=false}}};
const context={window:win,document:{body,documentElement:html},fullScreenViewport:{matches:true,addEventListener(){}},dialog,input:{addEventListener(){}},resizeComposer(){},requestAnimationFrame(fn){return 1}};
vm.createContext(context);
vm.runInContext(js.slice(begin,end)+'\nlockAgentPage();updateAgentViewport();',context);
assert.equal(props.get('--agent-visual-height'),'430px');
assert.equal(props.get('--agent-visual-top'),'175px');
assert.equal(dialog.classList['has-virtual-keyboard'],true);
assert.equal(body.style.overflow,'hidden');
assert.notEqual(body.style.position,'fixed','Never fix body positioning while Safari shows the keyboard');
assert.equal(stops,1);
vm.runInContext('unlockAgentPage()',context);
assert.equal(body.style.overflow,'visible');
assert.equal(html.style.overflow,'visible');
assert.equal(starts,1);
assert(css.includes('.portfolio-search .search-form'),'Composer remains present in the mobile layout');
assert(css.includes('.portfolio-search .agent-actions-toggle:focus:not(:focus-visible)'));
assert(!css.includes('.agent-preview-action{'),'Obsolete project-preview button CSS removed');
console.log('Mobile keyboard viewport, scroll unlock, focus treatment, and unused-style regression checks passed.');
